#!/usr/bin/env python
"""Generate include/engine/unicode_tables.h from Python's unicodedata.

The Qwen3.5 pre-tokenizer regex (llama.cpp LLAMA_VOCAB_PRE_TYPE_QWEN35) needs
three Unicode general-category predicates on codepoints:

  \\p{L}  letters        (Lu Ll Lt Lm Lo)
  \\p{N}  numbers        (Nd Nl No)
  \\p{M}  combining marks(Mn Mc Me)

plus the exact `\\s` whitespace set llama.cpp uses (Unicode White_Space).
The engine has no ICU dependency, so the ranges are baked into a sorted table
and looked up with a binary search.

Usage: python tools/gen_unicode_tables.py            # writes the header
       python tools/gen_unicode_tables.py --check    # verify it is up to date
"""
from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path

HEADER = "include/engine/unicode_tables.h"

# llama.cpp unicode_cpt_flags bit values (src/unicode.h)
FLAG_UNDEFINED = 0x0001
FLAG_NUMBER = 0x0002
FLAG_LETTER = 0x0004
FLAG_SEPARATOR = 0x0008
FLAG_MARK = 0x0010
FLAG_PUNCTUATION = 0x0020
FLAG_SYMBOL = 0x0040
FLAG_CONTROL = 0x0080

_CATEGORY_FLAGS = {
    "Lu": FLAG_LETTER, "Ll": FLAG_LETTER, "Lt": FLAG_LETTER,
    "Lm": FLAG_LETTER, "Lo": FLAG_LETTER,
    "Nd": FLAG_NUMBER, "Nl": FLAG_NUMBER, "No": FLAG_NUMBER,
    "Mn": FLAG_MARK, "Mc": FLAG_MARK, "Me": FLAG_MARK,
    "Zs": FLAG_SEPARATOR, "Zl": FLAG_SEPARATOR, "Zp": FLAG_SEPARATOR,
    "Pc": FLAG_PUNCTUATION, "Pd": FLAG_PUNCTUATION, "Ps": FLAG_PUNCTUATION,
    "Pe": FLAG_PUNCTUATION, "Pi": FLAG_PUNCTUATION, "Pf": FLAG_PUNCTUATION,
    "Po": FLAG_PUNCTUATION,
    "Sm": FLAG_SYMBOL, "Sc": FLAG_SYMBOL, "Sk": FLAG_SYMBOL, "So": FLAG_SYMBOL,
    "Cc": FLAG_CONTROL, "Cf": FLAG_CONTROL, "Cs": FLAG_CONTROL, "Co": FLAG_CONTROL,
    "Cn": FLAG_UNDEFINED,  # unassigned: llama.cpp still marks the flag (nonzero)
}

# Whitespace set copied from llama.cpp src/unicode-data.cpp
# (unicode_set_whitespace); Unicode White_Space property.
WHITESPACE = [
    0x000009, 0x00000A, 0x00000B, 0x00000C, 0x00000D, 0x000020, 0x000085,
    0x0000A0, 0x001680,
    0x002000, 0x002001, 0x002002, 0x002003, 0x002004, 0x002005, 0x002006,
    0x002007, 0x002008, 0x002009, 0x00200A,
    0x002028, 0x002029, 0x00202F, 0x00205F, 0x003000,
]


def category_flags(cp: int) -> int:
    return _CATEGORY_FLAGS[unicodedata.category(chr(cp))]


def build_ranges() -> list[tuple[int, int, int]]:
    ranges: list[tuple[int, int, int]] = []
    start = 0
    cur = -1
    for cp in range(0x110000):
        f = category_flags(cp)
        if cur < 0:
            cur, start = f, cp
        elif f != cur:
            ranges.append((start, cp - 1, cur))
            start, cur = cp, f
    ranges.append((start, 0x10FFFF, cur))
    return ranges


def render() -> str:
    ranges = build_ranges()
    ver = unicodedata.unidata_version
    out = []
    out.append("// Generated by tools/gen_unicode_tables.py -- do not edit by hand.")
    out.append(f"// Unicode data from Python unicodedata {ver}.")
    out.append("//")
    out.append("// llama.cpp-compatible unicode_cpt_flags: general-category bits for every")
    out.append("// codepoint plus the exact whitespace set.  Sorted ranges, binary search.")
    out.append("#pragma once")
    out.append("")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace engine {")
    out.append("namespace unicode {")
    out.append("")
    out.append("enum Flags : uint8_t {")
    out.append("  kUndefined = 0x01,")
    out.append("  kNumber = 0x02,")
    out.append("  kLetter = 0x04,")
    out.append("  kSeparator = 0x08,")
    out.append("  kMark = 0x10,")
    out.append("  kPunctuation = 0x20,")
    out.append("  kSymbol = 0x40,")
    out.append("  kControl = 0x80,")
    out.append("};")
    out.append("")
    out.append("struct Range {")
    out.append("  uint32_t first;")
    out.append("  uint32_t last;   // inclusive")
    out.append("  uint8_t flags;   // llama.cpp unicode_cpt_flags bits")
    out.append("};")
    out.append("")
    out.append(f"constexpr Range kRanges[] = {{  // {len(ranges)} ranges")
    for first, last, flags in ranges:
        out.append("    {0x%06X, 0x%06X, %d}," % (first, last, flags))
    out.append("};")
    out.append("constexpr uint32_t kRangeCount = sizeof(kRanges) / sizeof(kRanges[0]);")
    out.append("")
    out.append("// Codepoint flags; 0 for unassigned codepoints and spaces/punctuation.")
    out.append("inline uint8_t flags_of(uint32_t cp) {")
    out.append("  uint32_t lo = 0, hi = kRangeCount;")
    out.append("  while (lo < hi) {")
    out.append("    const uint32_t mid = (lo + hi) / 2;")
    out.append("    if (cp < kRanges[mid].first) hi = mid;")
    out.append("    else if (cp > kRanges[mid].last) lo = mid + 1;")
    out.append("    else return kRanges[mid].flags;")
    out.append("  }")
    out.append("  return 0;")
    out.append("}")
    out.append("")
    out.append("inline bool is_punct_or_symbol(uint32_t cp) {")
    out.append("  return (flags_of(cp) & (kPunctuation | kSymbol)) != 0;")
    out.append("}")
    out.append("inline bool is_letter(uint32_t cp) { return (flags_of(cp) & kLetter) != 0; }")
    out.append("inline bool is_number(uint32_t cp) { return (flags_of(cp) & kNumber) != 0; }")
    out.append("inline bool is_mark(uint32_t cp) { return (flags_of(cp) & kMark) != 0; }")
    out.append("")
    out.append("// llama.cpp unicode_cpt_flags::is_whitespace (Unicode White_Space).")
    out.append("inline bool is_whitespace(uint32_t cp) {")
    out.append("  switch (cp) {")
    for cp in WHITESPACE:
        out.append("    case 0x%06X:" % cp)
    out.append("      return true;")
    out.append("    default:")
    out.append("      return false;")
    out.append("  }")
    out.append("}")
    out.append("")
    out.append("}  // namespace unicode")
    out.append("}  // namespace engine")
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="only verify the header is current")
    args = ap.parse_args()
    root = Path(__file__).resolve().parent.parent
    path = root / HEADER
    text = render()
    if args.check:
        if not path.exists():
            print(f"{HEADER}: missing")
            return 1
        if path.read_text(encoding="utf-8") != text:
            print(f"{HEADER}: OUT OF DATE (re-run tools/gen_unicode_tables.py)")
            return 1
        print(f"{HEADER}: up to date ({unicodedata.unidata_version})")
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    n = text.count("\n    {0x")
    print(f"wrote {HEADER}: {n} ranges (Unicode {unicodedata.unidata_version})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
